create or replace function public.guard_active_payment_allocations()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if exists (
    select 1
    from public.payment_allocations existing
    join public.payments existing_payment
      on existing_payment.id = existing.payment_id
    where existing.installment_schedule_id = new.installment_schedule_id
      and existing_payment.status in ('Pending', 'Needs Reupload', 'Confirmed')
      and existing.payment_id <> coalesce(new.payment_id, -1)
  ) then
    raise exception 'Cicilan sudah memiliki pengajuan aktif atau terkonfirmasi.';
  end if;
end;
$$;

drop trigger if exists trg_guard_active_payment_allocations on public.payment_allocations;
create trigger trg_guard_active_payment_allocations
before insert or update of payment_id, installment_schedule_id
on public.payment_allocations
for each row execute function public.guard_active_payment_allocations();

create or replace function public.create_admin_payment_with_allocations(
  p_customer_id bigint,
  p_lot_id bigint,
  p_transaction_id bigint,
  p_payment_date date,
  p_amount bigint,
  p_payment_method text,
  p_payment_category text,
  p_reference_number text,
  p_proof_path text,
  p_note text,
  p_allocations jsonb default '[]'::jsonb
)
returns public.payments
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin_id uuid := auth.uid();
  v_transaction public.lot_transactions%rowtype;
  v_payment public.payments%rowtype;
  v_payment_category text;
  v_allocation jsonb;
  v_schedule public.installment_schedules%rowtype;
  v_expected_total bigint := 0;
  v_index integer := 0;
begin
  if v_admin_id is null or not exists (
    select 1 from public.profiles
    where id = v_admin_id and role in ('admin', 'owner')
  ) then
    raise exception 'Hanya Admin atau Owner yang dapat membuat pembayaran manual.';
  end if;

  select * into v_transaction
  from public.lot_transactions
  where id = p_transaction_id
    and customer_id = p_customer_id
    and lot_id = p_lot_id
  for update;

  if not found or v_transaction.status = 'Cancelled' then
    raise exception 'Transaksi tidak valid untuk pembayaran.';
  end if;

  if p_amount is null or p_amount <= 0 then
    raise exception 'Nominal pembayaran harus lebih dari nol.';
  end if;

  if nullif(btrim(coalesce(p_proof_path, '')), '') is null then
    raise exception 'Bukti pembayaran wajib tersedia.';
  end if;

  v_payment_category := p_payment_category;

  if v_transaction.payment_type = 'Cash' then
    if v_payment_category <> 'Cash Purchase' then
      raise exception 'Transaksi tunai hanya menerima pembayaran pelunasan.';
    end if;

    if coalesce(jsonb_array_length(p_allocations), 0) <> 0 then
      raise exception 'Pembayaran tunai tidak memiliki alokasi cicilan.';
    end if;

    if exists (
      select 1 from public.payments
      where transaction_id = p_transaction_id
        and payment_category = 'Cash Purchase'
        and status in ('Pending', 'Confirmed')
    ) then
      raise exception 'Pembayaran tunai sudah dikirim atau sudah lunas.';
    end if;

    if p_amount <> v_transaction.final_price then
      raise exception 'Nominal pelunasan harus sama dengan harga final SPK.';
    end if;
  elsif v_transaction.payment_type = 'Installment' then
    if v_payment_category <> 'Installment' then
      raise exception 'Pembayaran manual cicilan harus berkategori Installment.';
    end if;

    if coalesce(v_transaction.down_payment, 0) > 0 and not exists (
      select 1 from public.payments
      where transaction_id = p_transaction_id
        and payment_category = 'Down Payment'
        and status = 'Confirmed'
    ) then
      raise exception 'DP harus dikonfirmasi sebelum cicilan dapat dibayar.';
    end if;

    if coalesce(jsonb_array_length(p_allocations), 0) < 1 then
      raise exception 'Minimal satu jadwal cicilan harus dialokasikan.';
    end if;

    for v_allocation in select value from jsonb_array_elements(p_allocations)
    loop
      v_index := v_index + 1;

      select * into v_schedule
      from public.installment_schedules
      where id = (v_allocation->>'installment_schedule_id')::bigint
        and transaction_id = p_transaction_id
      for update;

      if not found then
        raise exception 'Jadwal cicilan tidak sesuai dengan transaksi.';
      end if;

      if v_schedule.status = 'Paid' then
        raise exception 'Cicilan yang dipilih sudah lunas.';
      end if;

      if v_schedule.installment_number <>
         (
           select min(s.installment_number)
           from public.installment_schedules s
           where s.transaction_id = p_transaction_id
             and s.status <> 'Paid'
         ) + v_index - 1
      then
        raise exception 'Jadwal cicilan harus dipilih secara berurutan.';
      end if;

      if exists (
        select 1
        from public.payment_allocations pa
        join public.payments p on p.id = pa.payment_id
        where pa.installment_schedule_id = v_schedule.id
          and p.status in ('Pending', 'Needs Reupload', 'Confirmed')
      ) then
        raise exception 'Cicilan sudah memiliki pengajuan aktif atau terkonfirmasi.';
      end if;

      v_expected_total := v_expected_total + v_schedule.amount;
    end loop;

    if p_amount <> v_expected_total then
      raise exception 'Nominal pembayaran tidak sama dengan total alokasi cicilan.';
    end if;
  else
    raise exception 'Metode pembayaran transaksi tidak dikenali.';
  end if;

  insert into public.payments (
    customer_id, lot_id, transaction_id, payment_date, amount,
    payment_method, payment_category, reference_number, proof_path,
    note, status, verified_at, verified_by
  ) values (
    p_customer_id, p_lot_id, p_transaction_id, coalesce(p_payment_date, current_date),
    p_amount, p_payment_method, v_payment_category, p_reference_number,
    p_proof_path, p_note, 'Pending', null, null
  )
  returning * into v_payment;

  if v_payment_category = 'Installment' then
    for v_allocation in select value from jsonb_array_elements(p_allocations)
    loop
      select * into v_schedule
      from public.installment_schedules
      where id = (v_allocation->>'installment_schedule_id')::bigint
        and transaction_id = p_transaction_id;

      insert into public.payment_allocations (
        payment_id, installment_schedule_id, allocated_amount
      ) values (
        v_payment.id, v_schedule.id, v_schedule.amount
      );
    end loop;
  end if;

  insert into public.payment_proof_history (
    payment_id, previous_proof_path, proof_path, file_name,
    mime_type, file_size_bytes, changed_by, change_type
  ) values (
    v_payment.id, null, p_proof_path, null, null, null, v_admin_id, 'Initial'
  );

  return v_payment;
end;
$$;

create or replace function public.review_payment_atomically(
  p_payment_id bigint,
  p_status text,
  p_review_note text,
  p_verified_by uuid
)
returns public.payments
language plpgsql
security definer
set search_path = public
as $$
declare
  v_reviewer uuid := auth.uid();
  v_payment public.payments%rowtype;
begin
  if v_reviewer is null or not exists (
    select 1 from public.profiles
    where id = v_reviewer and role in ('admin', 'owner')
  ) then
    raise exception 'Hanya Admin atau Owner yang dapat memverifikasi pembayaran.';
  end if;

  if p_status not in ('Confirmed', 'Rejected', 'Needs Reupload') then
    raise exception 'Status verifikasi tidak valid.';
  end if;

  select * into v_payment
  from public.payments
  where id = p_payment_id
  for update;

  if not found then
    raise exception 'Pembayaran tidak ditemukan.';
  end if;

  if v_payment.status <> 'Pending' then
    raise exception 'Pembayaran sudah ditinjau atau statusnya telah berubah.';
  end if;

  update public.payments
  set
    status = p_status,
    review_note = nullif(btrim(coalesce(p_review_note, '')), ''),
    verified_at = case when p_status = 'Confirmed' then now() else null end,
    verified_by = case when p_status = 'Confirmed' then v_reviewer else null end
  where id = p_payment_id
  returning * into v_payment;

  insert into public.payment_status_history (
    payment_id, old_status, new_status, review_note, changed_by
  ) values (
    p_payment_id, 'Pending', p_status,
    nullif(btrim(coalesce(p_review_note, '')), ''), v_reviewer
  );

  return v_payment;
end;
$$;

create or replace function public.replace_payment_proof_atomically(
  p_payment_id bigint,
  p_new_proof_path text,
  p_file_name text,
  p_mime_type text,
  p_file_size_bytes bigint
)
returns public.payments
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_payment public.payments%rowtype;
begin
  if v_user is null then
    raise exception 'Sesi login tidak valid.';
  end if;

  select p.* into v_payment
  from public.payments p
  join public.customers c on c.id = p.customer_id
  where p.id = p_payment_id
    and c.user_id = v_user
  for update;

  if not found then
    raise exception 'Pembayaran tidak ditemukan atau bukan milik akun Anda.';
  end if;

  if v_payment.status <> 'Needs Reupload' then
    raise exception 'Pembayaran tidak sedang menunggu upload ulang.';
  end if;

  if nullif(btrim(coalesce(p_new_proof_path, '')), '') is null then
    raise exception 'Path bukti pembayaran baru wajib tersedia.';
  end if;

  insert into public.payment_proof_history (
    payment_id, previous_proof_path, proof_path, file_name,
    mime_type, file_size_bytes, changed_by, change_type
  ) values (
    v_payment.id, v_payment.proof_path, p_new_proof_path,
    p_file_name, p_mime_type, p_file_size_bytes, v_user, 'Reupload'
  );

  update public.payments
  set
    proof_path = p_new_proof_path,
    status = 'Pending',
    verified_at = null,
    verified_by = null
  where id = p_payment_id
  returning * into v_payment;

  if v_payment.spk_request_id is not null then
    update public.spk_request_documents
    set
      file_path = p_new_proof_path,
      file_name = p_file_name,
      mime_type = p_mime_type,
      file_size_bytes = p_file_size_bytes
    where spk_request_id = v_payment.spk_request_id
      and document_type = 'Payment Proof';
  end if;

  insert into public.payment_status_history (
    payment_id, old_status, new_status, review_note, changed_by
  ) values (
    p_payment_id, 'Needs Reupload', 'Pending', null, v_user
  );

  return v_payment;
end;
$$;

