drop policy if exists "Client reupload own SPK payment proof" on storage.objects;
create policy "Client reupload own SPK payment proof"
on storage.objects for insert to authenticated
with check (
  bucket_id = 'spk-client-private-documents'
  and (storage.foldername(name))[1] = auth.uid()::text
  and exists (
    select 1
    from public.payments p
    join public.customers c on c.id = p.customer_id
    join public.spk_requests sr on sr.id = p.spk_request_id
    where p.status = 'Needs Reupload'
      and p.payment_category = 'Booking'
      and sr.submission_source = 'Client'
      and sr.submitted_by = auth.uid()
      and c.user_id = auth.uid()
      and sr.id = ((storage.foldername(name))[2])::bigint
  )
);

