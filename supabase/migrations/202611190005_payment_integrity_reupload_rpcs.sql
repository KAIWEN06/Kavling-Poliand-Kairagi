create table if not exists public.payment_proof_history (
  id bigint generated by default as identity primary key,
  payment_id bigint not null references public.payments(id) on delete cascade,
  previous_proof_path text,
  proof_path text not null,
  file_name text,
  mime_type text,
  file_size_bytes bigint check (file_size_bytes is null or file_size_bytes >= 0),
  changed_by uuid references public.profiles(id),
  change_type text not null check (change_type in ('Initial', 'Reupload', 'Correction')),
  created_at timestamptz not null default now()
);

create table if not exists public.payment_status_history (
  id bigint generated by default as identity primary key,
  payment_id bigint not null references public.payments(id) on delete cascade,
  old_status text,
  new_status text not null,
  review_note text,
  changed_by uuid references public.profiles(id),
  created_at timestamptz not null default now()
);

