begin;

create table if not exists public.booking_fee_refunds (
  id bigint generated by default as identity primary key,
  payment_id bigint not null references public.payments(id) on delete restrict,
  spk_request_id bigint not null references public.spk_requests(id) on delete restrict,
  customer_id bigint not null references public.customers(id) on delete restrict,
  amount bigint not null check (amount > 0),
  status text not null default 'Pending Refund'
    check (status in ('Pending Refund', 'Refunded')),
  proof_path text,
  refund_method text,
  refund_note text,
  refunded_at timestamptz,
  refunded_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (payment_id)
);

insert into public.booking_fee_refunds (
  payment_id,
  spk_request_id,
  customer_id,
  amount,
  status
)
select
  p.id,
  p.spk_request_id,
  p.customer_id,
  p.amount,
  'Pending Refund'
from public.payments p
join public.spk_requests sr on sr.id = p.spk_request_id
where p.payment_category = 'Booking'
  and p.status in ('Pending', 'Needs Reupload', 'Confirmed', 'Rejected')
  and sr.status = 'Rejected'
  and p.customer_id is not null
  and p.amount > 0
on conflict (payment_id) do nothing;

alter table public.booking_fee_refunds enable row level security;

drop policy if exists "Client read own booking fee refunds" on public.booking_fee_refunds;
create policy "Client read own booking fee refunds"
on public.booking_fee_refunds for select to authenticated
using (
  customer_id in (
    select c.id
    from public.customers c
    where c.user_id = auth.uid()
  )
);

drop policy if exists "Admin manage booking fee refunds" on public.booking_fee_refunds;
create policy "Admin manage booking fee refunds"
on public.booking_fee_refunds for all to authenticated
using (
  exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and role in ('admin', 'owner')
  )
)
with check (
  exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and role in ('admin', 'owner')
  )
);

create or replace function public.ensure_booking_fee_refund(
  p_payment_id bigint
)
returns public.booking_fee_refunds
language plpgsql
security definer
set search_path = public
as $$
declare
  v_payment public.payments%rowtype;
  v_refund public.booking_fee_refunds%rowtype;
begin
  select * into v_payment
  from public.payments
  where id = p_payment_id
    and payment_category = 'Booking';

  if not found then
    raise exception 'Pembayaran Booking Fee tidak ditemukan.';
  end if;

  if v_payment.status not in ('Pending', 'Needs Reupload', 'Rejected', 'Confirmed') then
    raise exception 'Status pembayaran tidak mendukung pencatatan pengembalian.';
  end if;

  if v_payment.spk_request_id is null
    or v_payment.customer_id is null
    or coalesce(v_payment.amount, 0) <= 0
  then
    raise exception 'Data pembayaran Booking Fee tidak lengkap.';
  end if;

  insert into public.booking_fee_refunds (
    payment_id,
    spk_request_id,
    customer_id,
    amount,
    status
  ) values (
    v_payment.id,
    v_payment.spk_request_id,
    v_payment.customer_id,
    v_payment.amount,
    'Pending Refund'
  )
  on conflict (payment_id) do update
  set
    amount = excluded.amount,
    updated_at = now()
  returning * into v_refund;

  return v_refund;
end;
$$;

create or replace function public.record_booking_fee_refund(
  p_payment_id bigint,
  p_proof_path text,
  p_refund_method text,
  p_refund_note text
)
returns public.booking_fee_refunds
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor uuid := auth.uid();
  v_refund public.booking_fee_refunds%rowtype;
begin
  if v_actor is null or not exists (
    select 1
    from public.profiles
    where id = v_actor
      and role in ('admin', 'owner')
  ) then
    raise exception 'Hanya Admin atau Owner yang dapat mencatat pengembalian.';
  end if;

  if nullif(btrim(coalesce(p_proof_path, '')), '') is null then
    raise exception 'Bukti pengembalian wajib diunggah.';
  end if;

  v_refund := public.ensure_booking_fee_refund(p_payment_id);

  update public.booking_fee_refunds
  set
    status = 'Refunded',
    proof_path = p_proof_path,
    refund_method = nullif(btrim(coalesce(p_refund_method, '')), ''),
    refund_note = nullif(btrim(coalesce(p_refund_note, '')), ''),
    refunded_at = now(),
    refunded_by = v_actor,
    updated_at = now()
  where id = v_refund.id
  returning * into v_refund;

  return v_refund;
end;
$$;

create or replace function public.create_booking_fee_refund_on_spk_rejection()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_payment record;
begin
  if new.status <> 'Rejected'
    or old.status is not distinct from new.status
  then
    return new;
  end if;

  for v_payment in
    select id
    from public.payments
    where spk_request_id = new.id
      and payment_category = 'Booking'
      and status in ('Pending', 'Needs Reupload', 'Confirmed', 'Rejected')
  loop
    perform public.ensure_booking_fee_refund(v_payment.id);
  end loop;

  return new;
end;
$$;

drop trigger if exists trg_create_booking_fee_refund_on_spk_rejection on public.spk_requests;
create trigger trg_create_booking_fee_refund_on_spk_rejection
after update of status on public.spk_requests
for each row execute function public.create_booking_fee_refund_on_spk_rejection();

revoke all on function public.ensure_booking_fee_refund(bigint) from public, anon;
revoke all on function public.record_booking_fee_refund(bigint,text,text,text) from public, anon;

grant execute on function public.record_booking_fee_refund(bigint,text,text,text) to authenticated;

drop policy if exists "Admin upload booking fee refund proof" on storage.objects;
create policy "Admin upload booking fee refund proof"
on storage.objects for insert to authenticated
with check (
  bucket_id = 'payment-proofs'
  and exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and role in ('admin', 'owner')
  )
);

drop policy if exists "Client read own booking fee refund proof" on storage.objects;
create policy "Client read own booking fee refund proof"
on storage.objects for select to authenticated
using (
  bucket_id = 'payment-proofs'
  and (
    exists (
      select 1
      from public.booking_fee_refunds r
      join public.customers c on c.id = r.customer_id
      where c.user_id = auth.uid()
        and (storage.foldername(name))[1] = 'refund'
        and r.spk_request_id = ((storage.foldername(name))[2])::bigint
    )
    or exists (
      select 1
      from public.profiles
      where id = auth.uid()
        and role in ('admin', 'owner')
    )
  )
);

commit;
